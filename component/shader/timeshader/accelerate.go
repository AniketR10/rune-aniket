//	···························xxx············································
//	·······················xxxx···············································
//	·····················xx···················································
//	················xxxxx·····················································
//	··········xxxxxx··························································
//	xxxxxxxxxx++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
func Accelerate(baseShader shader.Shader) shader.Shader {
	return accelerate(baseShader)
}

func accelerate(baseShader shader.Shader) *timeShader {
	return &timeShader{baseShader, funcTimeRemapper(
		func(frame, total int) int {
			dur := float64(total - 1)
			t := float64(frame) / dur
			tt := t * t
			ret := int(math.Round(dur * tt))
			return ret
		},
	)}
}
